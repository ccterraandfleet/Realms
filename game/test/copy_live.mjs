import puppeteer from "puppeteer-core";
const b = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", args: ["--no-sandbox","--disable-dev-shm-usage"], defaultViewport: { width: 1300, height: 850 } });
await b.defaultBrowserContext().overridePermissions("https://ccterraandfleet.github.io", ["clipboard-read","clipboard-write","clipboard-sanitized-write"]);
const p = await b.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push(e.message.slice(0, 160)));
await p.goto("https://ccterraandfleet.github.io/Realms/?seed=7", { waitUntil: "load", timeout: 90000 });
await p.waitForSelector(".lobby-copy", { timeout: 60000 });
await p.click(".lobby-copy");
await new Promise((r) => setTimeout(r, 300));
console.log("lobby:", await p.evaluate(() => document.querySelector(".lobby-copy").textContent), "|", await p.evaluate(() => navigator.clipboard.readText()));
await p.click(".lobby-go");
await p.waitForSelector("#copy-invite", { timeout: 30000 });
await new Promise((r) => setTimeout(r, 400));
await p.click("#copy-invite");
await new Promise((r) => setTimeout(r, 300));
console.log("bar:", await p.evaluate(() => document.getElementById("copy-invite").textContent), "|", await p.evaluate(() => navigator.clipboard.readText()));
console.log("errors:", errs.length ? errs : "none");
await b.close();
